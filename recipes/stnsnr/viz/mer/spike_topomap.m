assert(~isempty(getenv('MYLFP_PROJECT_ROOT')), 'Set MYLFP_PROJECT_ROOT before running this script.');

%% MER spike unit coverage topomap
clear; clc; close("all");

script_dir = fileparts(mfilename('fullpath'));
repo_root = fileparts(fileparts(fileparts(fileparts(script_dir))));
addpath(fullfile(repo_root, 'src', 'viz', 'surface', 'render'));

%% File config
project = getenv('MYLFP_PROJECT_ROOT');
data_dir = fullfile(project, 'summary', 'stats', 'mer', 'spike', ...
    'topomap', 'cover', 'SNr');
data_path = fullfile(data_dir, 'spike_unit_cover.nii.gz');
df_contact_path = fullfile(data_dir, 'spike_unit_cover.csv');

if exist(data_path, 'file') ~= 2
    error('Missing coverage NIfTI: %s', data_path);
end
if exist(df_contact_path, 'file') ~= 2
    error('Missing coverage CSV: %s', df_contact_path);
end

df_contact = readtable(df_contact_path);

%% Surface config
cmap = [0.80, 0.80, 0.80;
        0.80, 0.80, 0.80];

patchObj = ea_nifti2patch(data_path, ...
    'TemplateNifti', [], ...
    'SurfaceMode', 'mask', ...
    'MaskThreshold', -9999, ...
    'MaskIsovalue', 0.5, ...
    'VolumeSmoothingSigmaMm', 0.0, ...
    'SurfaceSmoothingIters', 20, ...
    'SurfaceSmoothingMethod', 'taubin', ...
    'SurfaceSmoothingLambda', 0.5, ...
    'SurfaceSmoothingMu', -0.1, ...
    'Alpha', 0.3, ...
    'Colormap', cmap, ...
    'CLimMode', 'auto', ...
    'GeometryUpsampleFactor', 1, ...
    'ColorSampling', 'inside', ...
    'SampleDepthMm', 0.5, ...
    'ReduceFactor', 1);

fprintf('Created patch: %d faces, %d vertices. GeometrySource=%s, MaskThreshold=%.3f\n', ...
    size(patchObj.faces, 1), size(patchObj.vertices, 1), ...
    patchObj.geometry_source, patchObj.mask_threshold);

%% SNr views from volume_cover.m
vSNr1 = struct();
vSNr1.az        = 0.8823;
vSNr1.el        = 0.1224;
vSNr1.camva     = 0.5000;
vSNr1.camup     = [0 0 1];
vSNr1.camproj   = 'orthographic';
vSNr1.camtarget = [9.6266 -16.6089 -12.8113];
vSNr1.campos    = [-842.3468 -1.6138e+03 474.5999];

vSNr2 = struct();
vSNr2.az        = -0.8227;
vSNr2.el        = -0.1286;
vSNr2.camva     = 0.5000;
vSNr2.camup     = [0 0 1];
vSNr2.camproj   = 'orthographic';
vSNr2.camtarget = [9.1244 -16.2821 -12.1207];
vSNr2.campos    = [1.0473e+03 1.4861e+03 411.8152];

views = {vSNr1, vSNr2};

%% Overlay source coordinates
coords = [df_contact.MNI_x_flip, df_contact.MNI_y_flip, df_contact.MNI_z_flip];
radius = 0.127;
n_sphere = 100;
sphere_color = [0.95, 0.55, 0.20];

load([ea_space([],'atlases'), 'Custom_Ewert_Zhang_Middlebrooks0.05', ...
    filesep, 'atlas_index.mat']);
roi = atlases.roi{13, 1}.fv;
roi = reducepatch(roi, 0.5);

for view_idx = 1:numel(views)
    out_png = fullfile(data_dir, ['cover', num2str(view_idx), '.png']);

    [hFig, hAx] = ea_plot_patch_leaddbs(patchObj, ...
        'MissingDataMode', 'gray', ...
        'MissingDataBlendRings', 0, ...
        'ViewStruct', views{view_idx}, ...
        'FigureVisible', 'off', ...
        'FigureBackend', 'matlab', ...
        'FigurePosition', [100 100 1200 900], ...
        'StrictHeadless', true, ...
        'AddColorbar', true, ...
        'ColorbarUnits', 'normalized', ...
        'ColorbarPosition', [0.84 0.20 0.03 0.60], ...
        'ColorbarLabel', 'Coverage', ...
        'ColorbarLabelInterpreter', 'none', ...
        'ColorbarTickLabelInterpreter', 'none', ...
        'ColorbarLabelFontSize', 32, ...
        'ColorbarTickFontSize', 27, ...
        'ColorbarLineWidth', 1.0, ...
        'ColorbarTickColor', [0 0 0], ...
        'ColorbarLabelColor', [0 0 0], ...
        'ColorbarLabelOffset', 0.6, ...
        'MarkExtrema', false, ...
        'RASTriadFontSize', 27, ...
        'RASTriadLineWidth', 5, ...
        'RASTriadHeadSize', 1.0, ...
        'ExportFile', '', ...
        'ExportResolution', 600);

    axes(hAx); %#ok<LAXES>
    patch('Faces', roi.faces, 'Vertices', roi.vertices, ...
        'FaceColor', 'none', 'EdgeColor', [0.30, 0.30, 0.30], ...
        'EdgeAlpha', 0.4);
    add_spheres(coords, radius, n_sphere, 'FaceColor', sphere_color);

    drawnow;
    ea_export_figure_transparent(hFig, out_png, ...
        'Transparent', false, ...
        'BackgroundColor', [1 1 1], ...
        'Resolution', 600, ...
        'Renderer', 'opengl');

    fprintf('Saved %s\n', out_png);
    close(hFig);
end
